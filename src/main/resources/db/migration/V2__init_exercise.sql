-- Quyen module Exercise
-- ---------------------------------------------------------------------
INSERT INTO permissions (code, resource, action, description) VALUES
    ('EXERCISE:READ',   'EXERCISE', 'READ',   'Xem bai tap'),
    ('EXERCISE:WRITE',  'EXERCISE', 'WRITE',  'Tao / sua bai tap'),
    ('EXERCISE:DELETE', 'EXERCISE', 'DELETE', 'Xoa bai tap');

-- ADMIN: toan bo quyen EXERCISE (READ, WRITE, DELETE)
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.name = 'ADMIN'
  AND p.resource = 'EXERCISE';

-- TEACHER: doc + tao/sua bai tap (EXERCISE:READ + EXERCISE:WRITE)
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.name = 'TEACHER'
  AND p.resource = 'EXERCISE'
  AND p.action IN ('READ', 'WRITE');

-- EMPLOYEE: chi xem bai tap (EXERCISE:READ only)
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.name = 'EMPLOYEE'
  AND p.resource = 'EXERCISE'
  AND p.action = 'READ';
