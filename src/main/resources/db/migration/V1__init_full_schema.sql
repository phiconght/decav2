-- 2) De <-> Bai tap (join + diem + thu tu)
CREATE TABLE exam_exercises (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id     BIGINT NOT NULL REFERENCES exams (id)     ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercises (id) ON DELETE RESTRICT,
    sort_order  INT    NOT NULL DEFAULT 0,
    points      NUMERIC(6,2),
    CONSTRAINT uq_exam_exercise UNIQUE (exam_id, exercise_id)
);
CREATE INDEX idx_exam_exercises_exam ON exam_exercises (exam_id);

-- 3) Diem tung y cho bai Dung/Sai
CREATE TABLE exam_tf_item_scores (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_exercise_id BIGINT NOT NULL REFERENCES exam_exercises (id)   ON DELETE CASCADE,
    tf_item_id       BIGINT NOT NULL REFERENCES true_false_items (id) ON DELETE CASCADE,
    points           NUMERIC(6,2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_exam_tf_item UNIQUE (exam_exercise_id, tf_item_id)
);

-- 4) De <-> Lop
CREATE TABLE exam_classes (
    exam_id  BIGINT NOT NULL REFERENCES exams (id)   ON DELETE CASCADE,
    class_id BIGINT NOT NULL REFERENCES classes (id) ON DELETE RESTRICT,
    PRIMARY KEY (exam_id, class_id)
);

-- 5) De <-> Hoc sinh (chi dung cho SUPPLEMENTARY)
CREATE TABLE exam_students (
    exam_id BIGINT NOT NULL REFERENCES exams (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (exam_id, user_id)
);

