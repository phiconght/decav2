CREATE TABLE exam_question_result (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_student_id  BIGINT        NOT NULL REFERENCES exam_student (id) ON DELETE CASCADE,
    exam_exercise_id BIGINT        NOT NULL REFERENCES exam_exercises (id) ON DELETE CASCADE,
    earned           NUMERIC(6, 2) NOT NULL DEFAULT 0,
    max_points       NUMERIC(6, 2) NOT NULL DEFAULT 0,
    correct          BOOLEAN,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(100),
    updated_by       VARCHAR(100),
    CONSTRAINT uq_eqr_student_exercise UNIQUE (exam_student_id, exam_exercise_id)
);
CREATE INDEX idx_eqr_exam_student ON exam_question_result (exam_student_id);
CREATE INDEX idx_eqr_exam_exercise ON exam_question_result (exam_exercise_id);
