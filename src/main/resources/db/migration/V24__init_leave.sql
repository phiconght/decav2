-- TEACHER: READ + APPROVE
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE r.name = 'TEACHER' AND p.resource = 'LEAVE' AND p.action IN ('READ', 'APPROVE');

-- STUDENT + PARENT: READ + WRITE
