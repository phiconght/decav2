    ('SESSION_CONTENT:READ',  'SESSION_CONTENT', 'READ',  'Xem video/zoom cua buoi hoc'),
    ('SESSION_CONTENT:WRITE', 'SESSION_CONTENT', 'WRITE', 'Nhap video/zoom cho buoi hoc');

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE r.name IN ('ADMIN', 'EMPLOYEE', 'TEACHER') AND p.resource = 'SESSION_CONTENT';
