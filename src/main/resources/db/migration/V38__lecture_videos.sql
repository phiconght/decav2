CREATE TABLE lecture_videos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    youtube_url      VARCHAR(500) NOT NULL UNIQUE,
    description      TEXT,
    topic_id         BIGINT REFERENCES topics (id) ON DELETE SET NULL,
    thumbnail_url    VARCHAR(500),
    duration_seconds INT,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(100),
    updated_by       VARCHAR(100)
);
CREATE INDEX idx_lecture_videos_topic ON lecture_videos (topic_id);

CREATE TABLE session_videos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES class_sessions (id) ON DELETE CASCADE,
    video_id   BIGINT NOT NULL REFERENCES lecture_videos (id) ON DELETE RESTRICT,
    sort_order INT    NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ,
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    CONSTRAINT uq_session_video UNIQUE (session_id, video_id)
);
CREATE INDEX idx_session_videos_session ON session_videos (session_id);
CREATE INDEX idx_session_videos_video ON session_videos (video_id);

